"""
backtester.py
==============
Replays the exact signal logic from signals.py over historical data with
no lookahead bias, realistic next-open entry and gap-through fills, and
portfolio-level position limits.
"""

from dataclasses import dataclass, field
from typing import List, Dict, Optional, Sequence
import pandas as pd
import numpy as np

from signals import detect_validated_low, Signal
from config import StrategyConfig, BacktestConfig, DEFAULT_STRATEGY_CONFIG, DEFAULT_BACKTEST_CONFIG


@dataclass
class TradeResult:
    ticker: str
    signal: Signal
    entry_date: pd.Timestamp
    exit_date: pd.Timestamp
    actual_entry_price: float
    exit_price: float
    exit_reason: str  # "stop", "target", "time_exit"
    shares: float
    pnl: float
    r_multiple: float
    holding_days: int
    exit_idx: int = 0


@dataclass
class BacktestReport:
    trades: List[TradeResult] = field(default_factory=list)
    initial_capital: float = 100_000.0
    final_capital: float = 100_000.0
    max_drawdown_pct: float = 0.0
    skipped_due_to_capacity: int = 0

    @property
    def n_trades(self) -> int:
        return len(self.trades)

    @property
    def win_rate(self) -> float:
        if not self.trades:
            return 0.0
        wins = sum(1 for t in self.trades if t.pnl > 0)
        return wins / len(self.trades)

    @property
    def avg_r_multiple(self) -> float:
        if not self.trades:
            return 0.0
        return float(np.mean([t.r_multiple for t in self.trades]))

    @property
    def expectancy_r(self) -> float:
        return self.avg_r_multiple

    @property
    def max_consecutive_losses(self) -> int:
        max_streak = streak = 0
        for t in self.trades:
            if t.pnl <= 0:
                streak += 1
                max_streak = max(max_streak, streak)
            else:
                streak = 0
        return max_streak

    @property
    def profit_factor(self) -> float:
        gross_win = sum(t.pnl for t in self.trades if t.pnl > 0)
        gross_loss = abs(sum(t.pnl for t in self.trades if t.pnl < 0))
        if gross_loss == 0:
            return float("inf") if gross_win > 0 else 0.0
        return gross_win / gross_loss

    @property
    def total_return_pct(self) -> float:
        return (self.final_capital - self.initial_capital) / self.initial_capital

    def summary(self) -> str:
        if not self.trades:
            return "No trades were generated by this strategy in the tested period."
        exit_reasons = pd.Series([t.exit_reason for t in self.trades]).value_counts()
        lines = [
            f"Trades executed: {self.n_trades} (skipped at max capacity: {self.skipped_due_to_capacity})",
            f"Win rate: {self.win_rate:.1%}",
            f"Avg R multiple per trade: {self.avg_r_multiple:+.2f}R",
            f"Profit factor: {self.profit_factor:.2f}",
            f"Max consecutive losses: {self.max_consecutive_losses}",
            f"Portfolio return: {self.total_return_pct:+.1%} (${self.initial_capital:,.0f} -> ${self.final_capital:,.0f})",
            f"Max realized drawdown: {self.max_drawdown_pct:.1%}",
            f"Exit breakdown: " + ", ".join(f"{k}={v}" for k, v in exit_reasons.items()),
        ]

        flagged = [t for t in self.trades if t.signal.risk_warnings]
        clean = [t for t in self.trades if not t.signal.risk_warnings]
        if flagged and clean:
            flagged_r = float(np.mean([t.r_multiple for t in flagged]))
            clean_r = float(np.mean([t.r_multiple for t in clean]))
            flagged_wr = sum(1 for t in flagged if t.pnl > 0) / len(flagged)
            clean_wr = sum(1 for t in clean if t.pnl > 0) / len(clean)
            lines.append("")
            lines.append(
                f"Flagged trades (warnings attached): "
                f"{len(flagged)} trades, win rate {flagged_wr:.1%}, avg {flagged_r:+.2f}R"
            )
            lines.append(
                f"Clean trades (no risk warnings): "
                f"{len(clean)} trades, win rate {clean_wr:.1%}, avg {clean_r:+.2f}R"
            )
        return "\n".join(lines)

    def to_dataframe(self) -> pd.DataFrame:
        rows = []
        for t in self.trades:
            rows.append({
                "ticker": t.ticker,
                "signal_date": t.signal.as_of_date,
                "entry_date": t.entry_date,
                "exit_date": t.exit_date,
                "signal_entry_price": t.signal.entry_price,
                "actual_entry_price": t.actual_entry_price,
                "stop_price": t.signal.stop_price,
                "target_price": t.signal.target_price,
                "exit_price": t.exit_price,
                "exit_reason": t.exit_reason,
                "shares": t.shares,
                "pnl": t.pnl,
                "r_multiple": t.r_multiple,
                "holding_days": t.holding_days,
                "rr_planned": t.signal.rr_ratio,
                "target_method": t.signal.target_method,
                "volume_ratio_at_low": t.signal.volume_ratio_at_low,
                "risk_warnings": " | ".join(t.signal.risk_warnings) if t.signal.risk_warnings else "",
                "had_warnings": bool(t.signal.risk_warnings),
            })
        return pd.DataFrame(rows)


def _simulate_trade_forward(
    df: pd.DataFrame,
    signal: Signal,
    signal_idx: int,
    strat_cfg: StrategyConfig,
    bt_cfg: BacktestConfig,
    current_equity: float,
) -> Optional[TradeResult]:
    n = len(df)
    if bt_cfg.entry_on_next_open:
        entry_idx = signal_idx + 1
        if entry_idx >= n:
            return None
        raw_entry = float(df["Open"].iloc[entry_idx])
        if raw_entry <= signal.stop_price or raw_entry >= signal.target_price:
            return None

        # Opening confirmation gate: abort if morning gaps down past threshold
        gap_pct = (raw_entry - signal.entry_price) / signal.entry_price
        if gap_pct < -bt_cfg.max_gap_down_pct:
            return None
    else:
        entry_idx = signal_idx
        raw_entry = float(signal.entry_price)

    # Recalculate true risk and R:R at the actual fill price
    risk_per_share = raw_entry - signal.stop_price
    if risk_per_share <= 0:
        return None

    open_stop_dist_pct = risk_per_share / raw_entry
    if open_stop_dist_pct < strat_cfg.min_stop_pct:
        return None

    if bt_cfg.recheck_min_rr_at_open:
        open_reward = signal.target_price - raw_entry
        if open_reward <= 0 or (open_reward / risk_per_share) < strat_cfg.min_rr_ratio:
            return None

    entry_price_adj = raw_entry * (1 + bt_cfg.slippage_pct + bt_cfg.commission_pct)
    capital_at_risk = current_equity * bt_cfg.risk_per_trade_pct
    shares = capital_at_risk / risk_per_share

    exit_price = None
    exit_reason = "time_exit"
    exit_idx = min(entry_idx + bt_cfg.max_holding_days, n - 1)

    start_bar = entry_idx if bt_cfg.entry_on_next_open else entry_idx + 1
    for i in range(start_bar, min(entry_idx + 1 + bt_cfg.max_holding_days, n)):
        bar_open = float(df["Open"].iloc[i])
        bar_low = float(df["Low"].iloc[i])
        bar_high = float(df["High"].iloc[i])

        if i > entry_idx and bar_open <= signal.stop_price:
            exit_price = bar_open
            exit_reason = "stop"
            exit_idx = i
            break

        if i > entry_idx and bar_open >= signal.target_price:
            exit_price = bar_open
            exit_reason = "target"
            exit_idx = i
            break

        hit_stop = bar_low <= signal.stop_price
        hit_target = bar_high >= signal.target_price

        if hit_stop:
            exit_price = signal.stop_price
            exit_reason = "stop"
            exit_idx = i
            break
        if hit_target:
            exit_price = signal.target_price
            exit_reason = "target"
            exit_idx = i
            break

    if exit_price is None:
        exit_price = float(df["Close"].iloc[exit_idx])
        exit_reason = "time_exit"

    exit_price_adj = exit_price * (1 - bt_cfg.slippage_pct - bt_cfg.commission_pct)
    pnl_per_share = exit_price_adj - entry_price_adj
    pnl = pnl_per_share * shares
    r_multiple = pnl_per_share / risk_per_share

    return TradeResult(
        ticker=signal.ticker,
        signal=signal,
        entry_date=df.index[entry_idx],
        exit_date=df.index[exit_idx],
        actual_entry_price=raw_entry,
        exit_price=float(exit_price),
        exit_reason=exit_reason,
        shares=float(shares),
        pnl=float(pnl),
        r_multiple=float(r_multiple),
        holding_days=int(exit_idx - entry_idx),
        exit_idx=int(exit_idx),
    )


def backtest_ticker(
    df: pd.DataFrame,
    ticker: str,
    strat_cfg: StrategyConfig = DEFAULT_STRATEGY_CONFIG,
    bt_cfg: BacktestConfig = DEFAULT_BACKTEST_CONFIG,
    cooldown_days: int = 10,
    earnings_dates: Optional[Sequence[pd.Timestamp]] = None,
) -> List[TradeResult]:
    trades: List[TradeResult] = []
    n = len(df)
    i = strat_cfg.lookback_days
    last_low_date = None

    while i < n:
        sig = detect_validated_low(
            df, ticker, cfg=strat_cfg, as_of_idx=i, earnings_dates=earnings_dates
        )
        if sig is not None and sig.low_date != last_low_date:
            last_low_date = sig.low_date
            trade = _simulate_trade_forward(
                df, sig, i, strat_cfg, bt_cfg, bt_cfg.initial_capital
            )
            if trade is not None:
                trades.append(trade)
                i = trade.exit_idx + cooldown_days
            else:
                i += 1
        else:
            i += 1

    return trades


def backtest_universe(
    data: Dict[str, pd.DataFrame],
    strat_cfg: StrategyConfig = DEFAULT_STRATEGY_CONFIG,
    bt_cfg: BacktestConfig = DEFAULT_BACKTEST_CONFIG,
    progress: bool = True,
    earnings_map: Optional[Dict[str, Sequence[pd.Timestamp]]] = None,
) -> BacktestReport:
    raw_candidates: List[TradeResult] = []
    for ticker, df in data.items():
        if progress:
            print(f"[backtest] {ticker}...")
        try:
            ed = earnings_map.get(ticker) if earnings_map else None
            trades = backtest_ticker(df, ticker, strat_cfg, bt_cfg, earnings_dates=ed)
            raw_candidates.extend(trades)
        except Exception as e:
            print(f"[backtest] Error backtesting {ticker}: {e}")

    raw_candidates.sort(key=lambda t: (t.entry_date, -t.signal.rr_ratio))

    equity = bt_cfg.initial_capital
    peak_equity = equity
    max_dd = 0.0
    active_positions: List[TradeResult] = []
    executed_trades: List[TradeResult] = []
    skipped = 0

    for cand in raw_candidates:
        still_open = []
        for pos in active_positions:
            if pos.exit_date <= cand.entry_date:
                equity += pos.pnl
                peak_equity = max(peak_equity, equity)
                dd = (peak_equity - equity) / peak_equity if peak_equity > 0 else 0.0
                max_dd = max(max_dd, dd)
            else:
                still_open.append(pos)
        active_positions = still_open

        if len(active_positions) >= bt_cfg.max_concurrent_positions:
            skipped += 1
            continue

        scale_factor = equity / bt_cfg.initial_capital
        cand.shares *= scale_factor
        cand.pnl *= scale_factor

        active_positions.append(cand)
        executed_trades.append(cand)

    active_positions.sort(key=lambda t: t.exit_date)
    for pos in active_positions:
        equity += pos.pnl
        peak_equity = max(peak_equity, equity)
        dd = (peak_equity - equity) / peak_equity if peak_equity > 0 else 0.0
        max_dd = max(max_dd, dd)

    return BacktestReport(
        trades=executed_trades,
        initial_capital=bt_cfg.initial_capital,
        final_capital=equity,
        max_drawdown_pct=max_dd,
        skipped_due_to_capacity=skipped,
    )